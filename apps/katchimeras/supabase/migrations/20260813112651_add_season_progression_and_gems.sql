create or replace function private.register_season_event_v1(payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_season_id text := payload->>'season_id';
  v_client_event_id text := payload->>'client_event_id';
  v_event_type text := payload->>'event_type';
  v_source_hash text := payload->>'source_hash';
  v_local_date date := (payload->>'local_date')::date;
  v_occurred_at timestamptz := (payload->>'occurred_at')::timestamptz;
  v_xp integer;
  v_inserted integer;
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;
  if v_client_event_id is null or length(v_client_event_id) > 160 or v_source_hash is null or length(v_source_hash) > 128 then
    raise exception 'Invalid season event';
  end if;
  if v_local_date < current_date - 7 or v_local_date > current_date + 1 then raise exception 'Invalid season event date'; end if;
  if not exists (
    select 1 from public.economy_campaigns campaign
    where campaign.id = v_season_id and campaign.kind = 'season' and campaign.enabled
      and (campaign.starts_at is null or campaign.starts_at <= now())
      and (campaign.ends_at is null or campaign.ends_at > now())
  ) then return jsonb_build_object('credited', false, 'reason', 'season_disabled'); end if;

  v_xp := case v_event_type
    when 'capture' then 10 when 'companion_interaction' then 5 when 'merge' then 1
    when 'order_served' then 10 when 'goal_completed' then 20 when 'hatch' then 30
    when 'wisp_discovered' then 15 else null end;
  if v_xp is null then raise exception 'Unsupported season event'; end if;

  insert into public.economy_season_event_receipts
    (user_id, season_id, client_event_id, event_type, local_date, source_id_hash, occurred_at)
  values (v_user_id, v_season_id, v_client_event_id, v_event_type, v_local_date, v_source_hash, v_occurred_at)
  on conflict do nothing;
  get diagnostics v_inserted = row_count;
  if v_inserted = 0 then return jsonb_build_object('credited', false, 'reason', 'duplicate'); end if;

  insert into public.economy_season_progress (user_id, season_id, xp)
  values (v_user_id, v_season_id, v_xp)
  on conflict (user_id, season_id) do update set
    xp = public.economy_season_progress.xp + excluded.xp,
    updated_at = now();
  return jsonb_build_object('credited', true, 'xp', v_xp);
end;
$$;

create or replace function private.claim_season_reward_v1(target_season_id text, target_tier_id text, target_track text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_campaign public.economy_campaigns%rowtype;
  v_progress public.economy_season_progress%rowtype;
  v_tier jsonb;
  v_reward jsonb;
  v_required_xp integer;
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;
  if target_track not in ('free', 'premium') then raise exception 'Invalid season track'; end if;
  select * into v_campaign from public.economy_campaigns
    where id = target_season_id and kind = 'season' and enabled
      and (starts_at is null or starts_at <= now()) and (ends_at is null or ends_at > now());
  if v_campaign.id is null then return jsonb_build_object('ok', false, 'reason', 'season_disabled'); end if;
  select * into v_progress from public.economy_season_progress where user_id = v_user_id and season_id = target_season_id;
  select value into v_tier from jsonb_array_elements(coalesce(v_campaign.config->'tiers', '[]'::jsonb)) where value->>'id' = target_tier_id limit 1;
  if v_tier is null then return jsonb_build_object('ok', false, 'reason', 'invalid_tier'); end if;
  v_required_xp := coalesce((v_tier->>'xp')::integer, 0);
  if coalesce(v_progress.xp, 0) < v_required_xp then return jsonb_build_object('ok', false, 'reason', 'not_eligible'); end if;
  if target_track = 'premium' and not coalesce(v_progress.premium, false) then return jsonb_build_object('ok', false, 'reason', 'premium_required'); end if;
  v_reward := case target_track when 'free' then v_tier->'freeReward' else v_tier->'premiumReward' end;
  if v_reward is null then return jsonb_build_object('ok', false, 'reason', 'no_reward'); end if;

  insert into public.economy_season_claims (user_id, season_id, tier_id, track, reward)
  values (v_user_id, target_season_id, target_tier_id, target_track, v_reward)
  on conflict do nothing;
  if not found then return jsonb_build_object('ok', false, 'reason', 'already_claimed'); end if;

  if v_reward->>'kind' = 'gems' then
    insert into public.economy_gem_ledger (user_id, delta, reason, source_type, idempotency_key)
    values (v_user_id, (v_reward->>'amount')::integer, 'season_reward', 'season', 'season:' || target_season_id || ':' || target_tier_id || ':' || target_track);
  elsif v_reward->>'kind' = 'wisp' then
    insert into public.economy_collectible_grants (user_id, collectible_type, collectible_id, quantity, source, source_key)
    values (v_user_id, 'wisp', v_reward->>'wispId', 1, 'season', 'season:' || target_season_id || ':' || target_tier_id || ':' || target_track)
    on conflict do nothing;
  end if;
  return jsonb_build_object('ok', true, 'reward', v_reward);
end;
$$;

