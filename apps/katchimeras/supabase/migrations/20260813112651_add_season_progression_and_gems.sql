create table public.economy_gem_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  delta integer not null check (delta <> 0),
  reason text not null,
  source_type text not null,
  idempotency_key text not null,
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (user_id, idempotency_key)
);

create table public.economy_season_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  season_id text not null references public.economy_campaigns(id) on delete cascade,
  xp integer not null default 0 check (xp >= 0),
  premium boolean not null default false,
  updated_at timestamptz not null default now(),
  primary key (user_id, season_id)
);

create table public.economy_season_event_receipts (
  user_id uuid not null references auth.users(id) on delete cascade,
  season_id text not null references public.economy_campaigns(id) on delete cascade,
  client_event_id text not null,
  event_type text not null,
  local_date date not null,
  source_id_hash text not null,
  occurred_at timestamptz not null,
  created_at timestamptz not null default now(),
  primary key (user_id, season_id, client_event_id)
);

create table public.economy_season_claims (
  user_id uuid not null references auth.users(id) on delete cascade,
  season_id text not null references public.economy_campaigns(id) on delete cascade,
  tier_id text not null,
  track text not null check (track in ('free', 'premium')),
  reward jsonb not null check (jsonb_typeof(reward) = 'object'),
  claimed_at timestamptz not null default now(),
  primary key (user_id, season_id, tier_id, track)
);

create index economy_gems_user_created_idx on public.economy_gem_ledger (user_id, created_at desc);
create index economy_season_events_user_date_idx on public.economy_season_event_receipts (user_id, local_date desc);

alter table public.economy_gem_ledger enable row level security;
alter table public.economy_season_progress enable row level security;
alter table public.economy_season_event_receipts enable row level security;
alter table public.economy_season_claims enable row level security;

