import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdir, writeFile, readFile, readdir, access } from 'node:fs/promises';

const native = 'features/live-ops/generated';
await mkdir(`${native}/rulesets`, { recursive: true });
async function retain(source) {
  source = source.replace(/\r\n/g, '\n');
  const match = source.match(/^\/\/ Generated by build:verified-replay\. Do not edit\.\nexport const rulesetId = "(merge-v1-([a-f0-9]{64}))";\n/);
  if (!match || createHash('sha256').update(source.slice(match[0].length)).digest('hex') !== match[2]) throw new Error('Native ruleset snapshot failed integrity check');
  const path = `${native}/rulesets/${match[1]}.js`;
  try { await access(path); if ((await readFile(path, 'utf8')).replace(/\r\n/g, '\n') !== source) throw new Error('Immutable ruleset collision'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; await writeFile(path, source); }
  return match[1];
}
try { await retain(await readFile(`${native}/replay.js`, 'utf8')); }
catch (error) { if (error.code !== 'ENOENT') throw error; }

const output = await build({ stdin: { contents: "export * from './features/live-ops/replay'; export * from './features/live-ops/replay-handler';", resolveDir: process.cwd(), loader: 'ts' }, bundle: true, write: false,
  platform: 'neutral', format: 'esm', target: 'es2022', mainFields: ['module', 'main'],
  tsconfig: 'tsconfig.json', conditions: ['import', 'default'], metafile: true });
const code = output.outputFiles[0].text;
const rulesetId = `merge-v1-${createHash('sha256').update(code).digest('hex')}`;
const directory = 'supabase/functions/verify-merge/generated';
await mkdir(directory, { recursive: true });
await writeFile(`${directory}/replay.mjs`, code);
await writeFile(`${directory}/ruleset.json`, JSON.stringify({ rulesetId, protocol: 1, content: 'bundled-only' }, null, 2) + '\n');
// Checked-in native snapshot: isolated registries, and available to Metro on a clean checkout.
const snapshot = `// Generated by build:verified-replay. Do not edit.\nexport const rulesetId = ${JSON.stringify(rulesetId)};\n${code}`;
await retain(snapshot);
await writeFile(`${native}/replay.js`, snapshot);
const files = (await readdir(`${native}/rulesets`)).filter((name) => /^merge-v1-[a-f0-9]{64}\.js$/.test(name)).sort();
await mkdir(`${directory}/rulesets`, { recursive: true });
await writeFile(`${directory}/rulesets/package.json`, '{"type":"module"}\n');
for (const file of files) {
  const source = (await readFile(`${native}/rulesets/${file}`, 'utf8')).replace(/\r\n/g, '\n');
  if (await retain(source) !== file.slice(0, -3)) throw new Error('Ruleset filename does not match its content');
  await writeFile(`${directory}/rulesets/${file}`, source);
}
const registry = files.map((name, index) => `import * as r${index} from './rulesets/${name}';`).join('\n')
  + `\nexport const rulesetId = ${JSON.stringify(rulesetId)};\nexport const replayRulesets = [${files.map((_name, index) => `r${index}`).join(',')}];\nexport const resolveReplayRuleset = (id) => replayRulesets.find((runtime) => runtime.rulesetId === id);\n`;
await writeFile(`${native}/registry.js`, registry);
const workerRegistry = files.map((name, index) => `import * as r${index} from '${name === `${rulesetId}.js` ? './replay.mjs' : `./rulesets/${name}`}';`).join('\n')
  + `\nexport const rulesetId = ${JSON.stringify(rulesetId)};\nexport const replayRulesets = [${files.map((name, index) => `{ ...r${index}, rulesetId: ${JSON.stringify(name.slice(0, -3))} }`).join(',')}];\n`;
await writeFile(`${directory}/registry.mjs`, workerRegistry);
console.log(`Built ${rulesetId} (${Math.round(code.length / 1024)} KiB). Existing checkpoints require their original bundle.`);
