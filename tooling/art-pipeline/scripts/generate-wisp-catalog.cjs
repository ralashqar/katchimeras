const {contentPath, assetSpecifier} = require('@incubator/art-pipeline/context');
const fs = require('node:fs');
const path = require('node:path');

const root = process.env.INCUBATOR_GAME_ROOT;
if (!root) throw new Error('Set INCUBATOR_GAME_ROOT to the selected game.');
const check = process.argv.includes('--check');
const base = readJson('data/wisps/catalog.json');
const planned = readJson('data/wisps/catalog.planned.json');
const items = [...base.items, ...planned.items].map(normalizeItem);
const catalog = { version: Math.max(base.version, planned.version), items };

validate(catalog);

const idsModule = `// Generated by scripts/generate-wisp-catalog.cjs. Do not edit.\nexport const WISP_IDS = ${JSON.stringify(items.map((item) => item.id), null, 2)} as const;\n`;
const ready = items.filter((item) => item.availability === 'ready');
const assetModule = `// Generated by scripts/generate-wisp-catalog.cjs. Expo requires literal asset paths. Do not edit.\nimport type { WispId } from '@/types/wisp';\n\nexport type WispAsset = { full: number; thumbnail: number };\n\nexport const WISP_ASSETS = {\n${ready.map((item) => `  ${JSON.stringify(item.id)}: { full: require('@incubator/art-wisps/${item.id}.webp'), thumbnail: require('@incubator/art-wisps/thumbnails/${item.id}.webp') },`).join('\n')}\n} as const satisfies Partial<Record<WispId, WispAsset>>;\n`;
const briefs = {
  version: catalog.version,
  items: items.filter((item) => item.availability === 'planned').map((item) => ({
    id: item.id, name: item.name, rarity: item.rarity,
    seriesId: item.seriesId ?? null, primaryFamilyId: item.primaryFamilyId ?? null,
    visualSummary: item.visualSummary, palette: item.palette,
    direction: 'Tiny floating creature, simple silhouette, one dominant concept, readable face, minimal limbs, transparent background; 20–30% of Egg Avatar height; do not resemble a full Katchimera.',
    requiredOutputs: [`${item.id}.png`, `${item.id}.webp`, `thumbnails/${item.id}.webp`],
  })),
};

emit('data/wisps/catalog.generated.json', `${JSON.stringify(catalog, null, 2)}\n`);
emit('data/wisps/art-briefs.generated.json', `${JSON.stringify(briefs, null, 2)}\n`);
emit('constants/wisp-ids.generated.ts', idsModule);
emit('constants/wisp-assets.generated.ts', assetModule);
console.log(`${check ? 'Verified' : 'Generated'} ${items.length} Wisps (${ready.length} ready, ${items.length - ready.length} planned).`);

function normalizeItem(item) {
  const ready = item.availability === 'ready';
  const semanticClass = item.semanticClass ?? (
    item.acquisition === 'experience' ? 'experience'
      : item.acquisition === 'achievement' ? 'achievement'
        : item.acquisition === 'game' ? 'game_reward'
          : item.acquisition === 'social' ? 'social'
            : item.acquisition === 'seasonal' ? 'seasonal' : 'cosmetic'
  );
  const normalized = {
    ...item,
    semanticClass,
    primaryAcquisition: item.primaryAcquisition ?? item.acquisition,
    primaryFamilyId: item.primaryFamilyId ?? null,
    affinityFamilyIds: item.affinityFamilyIds ?? [],
    seriesId: item.seriesId ?? null,
    giftPolicy: item.giftPolicy ?? (item.acquisition === 'premium' ? 'not_giftable' : 'duplicate_only'),
    duplicatePolicy: item.duplicatePolicy ?? (item.acquisition === 'premium' ? 'convert' : 'convert_or_gift'),
    assetRefs: ready ? {
      art: `assets/images/katchimeras/wisps/${item.id}.png`,
      runtime: `assets/images/katchimeras/wisps/${item.id}.webp`,
      thumbnail: `assets/images/katchimeras/wisps/thumbnails/${item.id}.webp`,
    } : null,
  };
  if (item.id === 'orbit') normalized.unlockRule = { ...item.unlockRule, target: 400 };
  return normalized;
}

function validate(document) {
  if (document.items.length !== 120) throw new Error(`Expected 120 Wisps, found ${document.items.length}`);
  const ids = new Set();
  for (const [index, item] of document.items.entries()) {
    if (!/^[a-z][a-z0-9-]*$/.test(item.id)) throw new Error(`Invalid Wisp id: ${item.id}`);
    if (ids.has(item.id)) throw new Error(`Duplicate Wisp id: ${item.id}`);
    ids.add(item.id);
    if (item.sortOrder !== index + 1) throw new Error(`Non-contiguous sortOrder for ${item.id}`);
    if (!['common', 'rare', 'epic', 'legendary'].includes(item.rarity)) throw new Error(`Invalid rarity for ${item.id}`);
    if (!['planned', 'ready'].includes(item.availability)) throw new Error(`Invalid availability for ${item.id}`);
    if (item.availability === 'planned' && item.assetRefs !== null) throw new Error(`Planned Wisp ${item.id} must not claim assets`);
    if (item.availability === 'ready') {
      for (const relative of Object.values(item.assetRefs)) {
        if (!fs.existsSync(contentPath(root, relative))) throw new Error(`Missing ready Wisp asset: ${relative}`);
      }
    }
  }
}

function readJson(relative) { return JSON.parse(fs.readFileSync(contentPath(root, relative), 'utf8')); }
function emit(relative, content) {
  const target = contentPath(root, relative);
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) throw new Error(`${relative} is stale. Run npm run wisps:catalog:generate.`);
    return;
  }
  fs.writeFileSync(target, content);
}
