create or replace function private.economy_grant_v1(
  target_user_id uuid,
  target_type text,
  target_id text,
  target_source text,
  target_source_key text,
  target_quantity integer default 1,
  target_provenance jsonb default '{}'::jsonb
) returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if target_user_id is null or target_quantity < 1 then raise exception 'Invalid grant'; end if;
  insert into public.economy_collectible_grants (user_id, collectible_type, collectible_id, quantity, source, source_key, provenance)
