create table public.economy_live_config (
  id text primary key,
  version integer not null check (version > 0),
  catalog_version integer not null check (catalog_version > 0),
  payload jsonb not null check (jsonb_typeof(payload) = 'object'),
  enabled boolean not null default false,
  min_app_version text,
  starts_at timestamptz,
  ends_at timestamptz,
  updated_at timestamptz not null default now()
);

create table public.economy_campaigns (
  id text primary key,
  kind text not null check (kind in ('shop', 'visitor', 'season', 'plus', 'bundle')),
  priority integer not null default 0,
  enabled boolean not null default false,
  starts_at timestamptz,
  ends_at timestamptz,
  min_catalog_version integer not null default 1,
  min_app_version text,
  config jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.economy_reward_rules (
  event_type text not null,
  rule_version integer not null check (rule_version > 0),
  essence_delta integer not null check (essence_delta > 0),
  enabled boolean not null default false,
  starts_at timestamptz,
  ends_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  primary key (event_type, rule_version)
);

create table public.economy_offers (
  id text primary key,
  campaign_id text references public.economy_campaigns(id) on delete cascade,
  collectible_type text not null check (collectible_type in ('wisp', 'avatar')),
  collectible_id text not null,
  currency text not null check (currency in ('essence', 'cash')),
  price integer not null check (price >= 0),
  enabled boolean not null default false,
  starts_at timestamptz,
  ends_at timestamptz,
  per_user_limit integer not null default 1 check (per_user_limit > 0),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.economy_collectible_grants (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  collectible_type text not null check (collectible_type in ('wisp', 'avatar')),
  collectible_id text not null,
  quantity integer not null default 1 check (quantity > 0),
  source text not null,
  source_key text not null,
  provenance jsonb not null default '{}'::jsonb,
  granted_at timestamptz not null default now(),
  revoked_at timestamptz,
  unique (user_id, collectible_type, collectible_id, source_key)
);

create table public.economy_essence_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  delta integer not null check (delta <> 0),
  reason text not null,
  source_type text not null,
  source_id_hash text,
  rule_version integer not null default 1 check (rule_version > 0),
  idempotency_key text not null,
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (user_id, idempotency_key)
);

create table public.economy_event_receipts (
