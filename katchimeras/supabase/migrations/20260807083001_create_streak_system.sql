create schema if not exists private;

create table public.streak_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  activation_date date not null default current_date,
  timezone text not null default 'UTC',
  current_streak integer not null default 0 check (current_streak >= 0),
  longest_streak integer not null default 0 check (longest_streak >= 0),
  lifetime_captured_days integer not null default 0 check (lifetime_captured_days >= 0),
  repairs_available integer not null default 0 check (repairs_available between 0 and 2),
  repairs_capacity integer not null default 2 check (repairs_capacity between 1 and 10),
  repair_earning_progress integer not null default 0 check (repair_earning_progress between 0 and 6),
  repairable_date date,
  declined_repair_date date,
  history_imported_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.streak_days (
  user_id uuid not null references auth.users(id) on delete cascade,
  local_date date not null,
  state text not null check (state in ('captured', 'missed', 'repaired')),
  first_capture_at timestamptz,
  qualifying_capture_type text,
  first_source_id_hash text,
  timezone text not null,
  repaired_at timestamptz,
  repair_source text check (repair_source in ('earned', 'support', 'migration')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, local_date)
);

create table public.streak_capture_receipts (
  user_id uuid not null references auth.users(id) on delete cascade,
  client_event_id text not null,
  local_date date not null,
  capture_type text not null,
  source_id_hash text not null,
  occurred_at timestamptz not null,
  timezone text not null,
  is_history boolean not null default false,
  created_at timestamptz not null default now(),
  primary key (user_id, client_event_id)
);

create table public.streak_repair_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  local_date date,
  delta integer not null check (delta in (-1, 1)),
  reason text not null check (reason in ('seven_captured_days', 'repair_used', 'support_adjustment')),
  created_at timestamptz not null default now()
);

create table public.streak_milestones (
  user_id uuid not null references auth.users(id) on delete cascade,
  milestone_days integer not null check (milestone_days in (3, 7, 14, 30, 50, 100, 365)),
  essence_reward integer not null check (essence_reward >= 0),
  reached_at timestamptz not null default now(),
  seen_at timestamptz,
  primary key (user_id, milestone_days)
);

create table public.streak_analytics_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_name text not null,
  platform text,
  properties jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index streak_days_user_date_idx on public.streak_days (user_id, local_date desc);
create index streak_receipts_user_date_idx on public.streak_capture_receipts (user_id, local_date desc);
create index streak_analytics_user_created_idx on public.streak_analytics_events (user_id, created_at desc);

alter table public.streak_profiles enable row level security;
alter table public.streak_days enable row level security;
alter table public.streak_capture_receipts enable row level security;
alter table public.streak_repair_ledger enable row level security;
alter table public.streak_milestones enable row level security;
alter table public.streak_analytics_events enable row level security;

